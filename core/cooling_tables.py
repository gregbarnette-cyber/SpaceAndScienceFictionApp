"""Bundled static cooling-track tables for the Phase U cooling-primary HZ calculator.

Each track maps a primary **mass** to a cooling sequence — a list of rows
``(age_gyr, teff_k, log10_l_lsun, radius_rsun)`` sorted ascending by age (i.e. the
star cools as you walk down the list: Teff and L both decrease monotonically).
``core.cooling`` interpolates these (bilinear in mass+age, log-space for L) to turn a
``(mass, age)`` request into ``(Teff, L, R)``; the radius column feeds the Roche
cross-check in CHZ mode.

These are **transcribed from the published cooling sequences**, not analytic fits — the
literature-faithful path chosen for Phase U. Every row is validated at transcription
against the radiative-equilibrium identity ``L/L_sun = (R/R_sun)^2 * (Teff/Teff_sun)^4``
(see ``tests/test_cooling_hz.py::test_table_closure_consistency``), which is a strong
integrity check: a mistranscribed Teff, L, or R breaks the identity.

Provenance is declared in ``_WD_TABLE_SOURCE`` / ``_BD_TABLE_SOURCE`` and surfaced in
every ``cooling-hz`` response's ``model_note`` and in ``docs/integration.md``.
"""

